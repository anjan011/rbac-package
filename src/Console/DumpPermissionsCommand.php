<?php

namespace Anjan011\RolesAndPermissions\Console;

use Anjan011\RolesAndPermissions\Models\Permission;
use Illuminate\Console\Command;
use Illuminate\Support\Facades\File;
use Illuminate\Support\Str;

class DumpPermissionsCommand extends Command
{
    /**
     * The name and signature of the console command.
     *
     * @var string
     */
    protected $signature = 'anjan011-roles-permissions:dump-permissions {--path= : The path where the constants file will be generated} {--prefix= : The prefix for the constant names}';

    /**
     * The console command description.
     *
     * @var string
     */
    protected $description = 'Dump all permissions from the database as PHP constants in a file';

    /**
     * Execute the console command.
     */
    public function handle(): int
    {
        $config = config('anjan001.roles-and-permissions.permissions_dump', []);

        $path = $this->option('path') ?: ($config['path'] ?? base_path('app/Constants/permissions.php'));
        $prefix = $this->option('prefix') ?: ($config['prefix'] ?? 'PERM');

        $this->info('Fetching permissions from the database...');
        $permissions = Permission::all();

        if ($permissions->isEmpty()) {
            $this->warn('No permissions found in the database. Please run the setup command or seed permissions first.');

            return 0;
        }

        $content = "<?php\n\n";
        $content .= "// This file is auto-generated by anjan011-roles-permissions:dump-permissions command.\n";
        $content .= "// Do not edit this file manually.\n\n";

        foreach ($permissions as $permission) {
            // Transform permission name to a constant-friendly name
            // Example: user.create -> PERM_USER_CREATE
            $normalizedName = str_replace(['.', '-'], '_', $permission->name);
            $constantName = Str::upper($prefix.'_'.$normalizedName);

            $content .= "const {$constantName} = '{$permission->name}';\n";
        }

        $directory = dirname($path);
        if (! File::isDirectory($directory)) {
            File::makeDirectory($directory, 0755, true);
        }

        File::put($path, $content);

        $this->info('Successfully dumped '.$permissions->count().' permissions as constants.');
        $this->info("Output file: {$path}");
        $this->comment("\nTo make these constants available globally, ensure this file is loaded in your application.");
        $this->comment("Example: add it to 'autoload.files' in your composer.json and run 'composer dump-autoload'.");

        return 0;
    }
}
